import { createElement, type SVGProps } from "react";

type Attrs = Record<string, string>;
type IconNode = Array<[string, Attrs]>;

function Icon({
  nodes,
  className,
  ...rest
}: { nodes: IconNode } & SVGProps<SVGSVGElement>) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
      className={className}
      {...rest}
    >
      {nodes.map(([tag, attrs], i) => createElement(tag, { ...attrs, key: i }))}
    </svg>
  );
}

function make(nodes: IconNode) {
  return function UiIcon(props: SVGProps<SVGSVGElement>) {
    return <Icon nodes={nodes} {...props} />;
  };
}

